package ui

import (
	"fmt"
	"strings"
)

type language string

const (
	langZH language = "zh"
	langEN language = "en"
)

// Localization is intentionally small and data-oriented so adding a locale
// does not couple business models to UI code.
type Localization struct {
	Lang language
}

func NewLocalization(tag string) Localization {
	if strings.HasPrefix(strings.ToLower(strings.TrimSpace(tag)), "en") {
		return Localization{Lang: langEN}
	}
	return Localization{Lang: langZH}
}

func (l Localization) T(key string) string {
	if l.Lang == langEN {
		if s, ok := english[key]; ok {
			return s
		}
	}
	if s, ok := chinese[key]; ok {
		return s
	}
	return key
}

func (l Localization) F(key string, args ...any) string {
	s := l.T(key)
	if len(args) == 0 {
		return s
	}
	// The app's locale files use "{n}"-style placeholders, while older
	// entries in this project use fmt's "%s"/"%d". Support both so a
	// request-count label can never leak "{n}%!(EXTRA ...)" into the UI.
	if !strings.Contains(s, "{") {
		return fmt.Sprintf(s, args...)
	}
	names := map[string][]string{
		"routing.contextCached":       {"cached", "fresh"},
		"routing.contextFree":         {"tokens"},
		"routing.contextFull":         {"pct"},
		"routing.contextTurns":        {"n"},
		"routing.contextTurnItem":     {"n"},
		"routing.contextEarlierTurns": {"n"},
		"routing.contextMoreItems":    {"n"},
		"routing.contextShowAll":      {"n"},
		"routing.storyAt":             {"time"},
		"routing.listScope":           {"n"},
		"routing.listScopeDay":        {"n", "day"},
		"routing.affinityTurn":        {"who", "agent", "n"},
		"routing.affinityCache":       {"who", "n"},
		"routing.affinitySession":     {"who"},
		"routing.groupStoryMembers":   {"agent", "name", "members"},
		"routing.ruleMatched":         {"n", "when"},
		"routing.ruleMatchedNoWhen":   {"n"},
		"routing.firstTokenStep":      {"ms"},
		"routing.nothingTried":        {"error"},
	}
	if ns, ok := names[key]; ok {
		for i, name := range ns {
			if i < len(args) {
				s = strings.ReplaceAll(s, "{"+name+"}", fmt.Sprint(args[i]))
			}
		}
		return s
	}
	return s
}

